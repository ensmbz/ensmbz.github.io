-- Run once in the Supabase SQL Editor after creating the public
-- Storage bucket named zayed-photos.

create table if not exists public.photo_submissions (
  id bigint generated by default as identity primary key,
  name text not null,
  image_url text not null,
  media_type text not null default 'image' check (media_type in ('image', 'video')),
  created_at timestamptz not null default now(),
  approved boolean not null default false
);

alter table public.photo_submissions enable row level security;

grant insert, select on public.photo_submissions to anon;
grant usage, select on sequence public.photo_submissions_id_seq to anon;

drop policy if exists "Anyone can submit photos for review" on public.photo_submissions;
create policy "Anyone can submit photos for review"
on public.photo_submissions
for insert
to anon
with check (
  char_length(name) between 1 and 60
  and char_length(image_url) <= 2048
  and media_type in ('image', 'video')
  and approved = false
);

drop policy if exists "Anyone can see approved photos" on public.photo_submissions;
create policy "Anyone can see approved photos"
on public.photo_submissions
for select
to anon
using (approved = true);

drop policy if exists "Anyone can upload to zayed-photos" on storage.objects;
create policy "Anyone can upload to zayed-photos"
on storage.objects
for insert
to anon
with check (bucket_id = 'zayed-photos');

-- Allow video clips (up to 50 MiB) alongside photos in the shared media bucket.
update storage.buckets
set file_size_limit = 52428800,
    allowed_mime_types = array['image/*', 'video/*']
where id = 'zayed-photos';
