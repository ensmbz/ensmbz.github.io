-- Recreate public website data after the old Supabase project was deleted.
-- Public submissions remain pending until an owner/moderator approves them.
create table if not exists public.photo_submissions (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 60),
  image_url text not null check (char_length(image_url) <= 2048),
  media_type text not null default 'image' check (media_type in ('image', 'video')),
  description text not null default '',
  created_at timestamptz not null default now(),
  approved boolean not null default false,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  discord_message_id text,
  discord_archive_message_id text,
  discord_comments_thread_id text
);
alter table public.photo_submissions add column if not exists description text not null default '';
alter table public.photo_submissions add column if not exists status text not null default 'pending';
alter table public.photo_submissions add column if not exists discord_message_id text;
alter table public.photo_submissions add column if not exists discord_archive_message_id text;
alter table public.photo_submissions add column if not exists discord_comments_thread_id text;
alter table public.photo_submissions enable row level security;
grant select, insert on public.photo_submissions to anon, authenticated;
grant usage, select on sequence public.photo_submissions_id_seq to anon, authenticated;
drop policy if exists "Anyone can submit photos for review" on public.photo_submissions;
create policy "Anyone can submit photos for review" on public.photo_submissions for insert to anon, authenticated
  with check (char_length(name) between 1 and 60 and char_length(image_url) <= 2048 and media_type in ('image','video') and approved = false and status = 'pending');
drop policy if exists "Anyone can see approved photos" on public.photo_submissions;
create policy "Anyone can see approved photos" on public.photo_submissions for select to anon, authenticated using (approved = true);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('zayed-photos', 'zayed-photos', true, null, array['image/*','video/*'])
on conflict (id) do update set public = true, file_size_limit = null, allowed_mime_types = array['image/*','video/*'];
drop policy if exists "Anyone can upload to zayed-photos" on storage.objects;
create policy "Anyone can upload to zayed-photos" on storage.objects for insert to anon, authenticated
  with check (bucket_id = 'zayed-photos');

create table if not exists public.site_control (
  id boolean primary key default true check (id is true),
  is_live boolean not null default true,
  updated_at timestamptz not null default now(),
  comments_channel_id text,
  takedown_channel_id text
);
alter table public.site_control add column if not exists comments_channel_id text;
alter table public.site_control add column if not exists takedown_channel_id text;
insert into public.site_control (id, is_live) values (true, true) on conflict (id) do nothing;
alter table public.site_control enable row level security;
grant select on public.site_control to anon, authenticated;
drop policy if exists "Anyone can read site status" on public.site_control;
create policy "Anyone can read site status" on public.site_control for select to anon, authenticated using (id is true);

create table if not exists public.photo_comments (
  id bigint generated by default as identity primary key,
  photo_id bigint not null references public.photo_submissions(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 40),
  body text not null check (char_length(body) between 1 and 400),
  status text not null default 'visible' check (status in ('visible','removed')),
  discord_message_id text,
  created_at timestamptz not null default now()
);
create index if not exists photo_comments_photo_created_at_idx on public.photo_comments(photo_id, created_at);
alter table public.photo_comments enable row level security;
grant select, insert on public.photo_comments to anon, authenticated;
grant usage, select on sequence public.photo_comments_id_seq to anon, authenticated;
drop policy if exists "public reads visible comments" on public.photo_comments;
create policy "public reads visible comments" on public.photo_comments for select to anon, authenticated using (status = 'visible');
drop policy if exists "public adds comments" on public.photo_comments;
create policy "public adds comments" on public.photo_comments for insert to anon, authenticated with check (status = 'visible');

create table if not exists public.photo_takedown_requests (
  id bigint generated by default as identity primary key,
  photo_id bigint not null references public.photo_submissions(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 40),
  reason text not null check (char_length(reason) between 1 and 500),
  status text not null default 'pending' check (status in ('pending','resolved')),
  created_at timestamptz not null default now()
);
create index if not exists photo_takedown_requests_status_idx on public.photo_takedown_requests(status, created_at);
alter table public.photo_takedown_requests enable row level security;
grant insert on public.photo_takedown_requests to anon, authenticated;
grant usage, select on sequence public.photo_takedown_requests_id_seq to anon, authenticated;
drop policy if exists "public adds takedown requests" on public.photo_takedown_requests;
create policy "public adds takedown requests" on public.photo_takedown_requests for insert to anon, authenticated with check (status = 'pending');

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 40),
  body text not null check (char_length(body) between 1 and 400),
  created_at timestamptz not null default now(),
  client_id text check (client_id is null or char_length(client_id) between 8 and 100)
);
alter table public.chat_messages add column if not exists client_id text;
alter table public.chat_messages enable row level security;
grant select, insert on public.chat_messages to anon, authenticated;
grant usage, select on sequence public.chat_messages_id_seq to anon, authenticated;
drop policy if exists "Anyone can read chat messages" on public.chat_messages;
create policy "Anyone can read chat messages" on public.chat_messages for select to anon, authenticated using (true);
drop policy if exists "Anyone can post chat messages" on public.chat_messages;
create policy "Anyone can post chat messages" on public.chat_messages for insert to anon, authenticated
  with check (char_length(trim(name)) between 1 and 40 and char_length(trim(body)) between 1 and 400);
do $$ begin
  if not exists (select 1 from pg_publication_tables where pubname='supabase_realtime' and schemaname='public' and tablename='chat_messages') then
    alter publication supabase_realtime add table public.chat_messages;
  end if;
end $$;

create table if not exists public.site_reports (id bigint generated by default as identity primary key, name text not null default 'Anonymous' check(char_length(name) between 1 and 40), body text not null check(char_length(body) between 1 and 1000), created_at timestamptz not null default now());
alter table public.site_reports enable row level security;
grant insert on public.site_reports to anon,authenticated;
grant usage,select on sequence public.site_reports_id_seq to anon,authenticated;
drop policy if exists "public submits reports" on public.site_reports;
create policy "public submits reports" on public.site_reports for insert to anon,authenticated with check(char_length(body) between 1 and 1000);
